/**
 * Settings → Privacy (decisions §5): the privacy statement and the no-recovery
 * warning as proper paragraphs instead of list subtitles. Pushed from the
 * About section, so it exists only inside the unlocked vault. Mirrors iOS
 * `PrivacyScreen`.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PrivacyScreen(onBack: () -> Unit) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.settings_privacy_title)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = stringResource(R.string.back_action),
                        )
                    }
                },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .padding(padding)
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 20.dp, vertical = 16.dp),
            verticalArrangement = Arrangement.spacedBy(20.dp),
        ) {
            Text(stringResource(R.string.settings_privacy_body), style = MaterialTheme.typography.bodyLarge)
            Text(stringResource(R.string.setup_no_recovery_body), style = MaterialTheme.typography.bodyLarge)
        }
    }
}
